-- MarketPulse PostgreSQL schema run by the PostgreSQL image on first initialization.
-- Prices use unconstrained NUMERIC to preserve Coinbase decimal precision.

CREATE TABLE IF NOT EXISTS tracked_products (
    id                    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    coinbase_product_id   TEXT NOT NULL UNIQUE
                          CHECK (coinbase_product_id = upper(coinbase_product_id))
                          CHECK (length(coinbase_product_id) BETWEEN 3 AND 32),
    base_currency         TEXT NOT NULL CHECK (base_currency = upper(base_currency)),
    quote_currency        TEXT NOT NULL CHECK (quote_currency = upper(quote_currency)),
    name                  TEXT NOT NULL CHECK (length(btrim(name)) BETWEEN 1 AND 80),
    is_active             BOOLEAN NOT NULL DEFAULT TRUE,
    source                TEXT NOT NULL DEFAULT 'manual'
                          CHECK (source IN ('bootstrap', 'manual')),
    created_at            TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at            TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (coinbase_product_id = base_currency || '-' || quote_currency)
);

