CREATE INDEX IF NOT EXISTS idx_tracked_products_active_name
    ON tracked_products (is_active, lower(name));

CREATE TABLE IF NOT EXISTS coinbase_market_catalog (
    coinbase_product_id   TEXT PRIMARY KEY,
    base_currency         TEXT NOT NULL,
    quote_currency        TEXT NOT NULL,
    display_name          TEXT NOT NULL,
    market_status         TEXT NOT NULL,
    trading_disabled      BOOLEAN NOT NULL DEFAULT FALSE,
    is_eligible           BOOLEAN NOT NULL DEFAULT FALSE,
    last_seen_at          TIMESTAMPTZ NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_coinbase_catalog_search
    ON coinbase_market_catalog (is_eligible, quote_currency, base_currency);

CREATE TABLE IF NOT EXISTS bootstrap_state (
    id                    SMALLINT PRIMARY KEY CHECK (id = 1),
    target_count          INTEGER NOT NULL DEFAULT 10 CHECK (target_count > 0),
    state                 TEXT NOT NULL DEFAULT 'not_started'
                          CHECK (state IN ('not_started', 'partial', 'complete')),
    seeded_count          INTEGER NOT NULL DEFAULT 0 CHECK (seeded_count >= 0),
    last_attempt_at       TIMESTAMPTZ,
    completed_at          TIMESTAMPTZ,
    last_error            TEXT
);

INSERT INTO bootstrap_state (id, target_count, state, seeded_count)
